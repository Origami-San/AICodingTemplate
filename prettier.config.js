// Локальные настройки Prettier.
// Этот файл действует только внутри текущего проекта и имеет приоритет над
// глобальными настройками расширения Prettier в VS Code.

module.exports = {
	// Использовать табы для отступов вместо пробелов.
	// Связано с `.editorconfig`: indent_style = tab.
	useTabs: true,

	// Визуальная ширина одного таба в редакторе.
	// Связано с `.editorconfig`: indent_size = 4.
	tabWidth: 4,

	// Формат конца строки: LF — кроссплатформенный стандарт для git-репозиториев.
	// Связано с `.editorconfig`: end_of_line = lf.
	endOfLine: "lf",

	// Желаемая максимальная длина строки.
	// Prettier переносит код и разметку около этой ширины, если синтаксис это позволяет.
	printWidth: 80,

	// Добавлять точку с запятой в конце JavaScript/TypeScript-инструкций.
	semi: true,

	// false = использовать двойные кавычки в JS/TS.
	// true = использовать одинарные кавычки.
	singleQuote: false,

	// Добавлять завершающую запятую там, где это совместимо с ES5:
	// объекты, массивы, импорты и экспорты.
	trailingComma: "es5",

	// Ставить пробелы внутри фигурных скобок объектов:
	// true => { name: value }
	// false => {name: value}
	bracketSpacing: true,

	// Всегда ставить скобки у параметров стрелочных функций:
	// always => (value) => value
	// avoid => value => value
	arrowParens: "always",

	// Не переносить закрывающую скобку HTML/JSX-тега на строку последнего атрибута.
	// false делает разметку более привычной и читаемой при нескольких атрибутах.
	bracketSameLine: false,

	// Не заставлять каждый HTML/JSX-атрибут переходить на отдельную строку.
	// Prettier сам решит, когда перенос нужен из-за printWidth.
	singleAttributePerLine: false,

	// Учитывать CSS-правила пробелов при форматировании HTML.
	// Это стандартное и самое безопасное поведение для обычной HTML-разметки.
	htmlWhitespaceSensitivity: "css",

	// Не переформатировать обычный текст в Markdown насильно.
	// Так проще сохранять ручные переносы строк в документации.
	proseWrap: "preserve",

	// Форматировать встроенный код, например CSS/JS внутри HTML или Markdown,
	// когда Prettier понимает вложенный язык.
	embeddedLanguageFormatting: "auto",
};
